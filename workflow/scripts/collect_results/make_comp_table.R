# ==============================================================================
# Script: make_comp_table.R
# Author: Filippo Gastaldello
# Date: 16/08/2026
# Description: 
#   Collect results from different methods and merge them in a single table to
#   allow direct comparison
#
# Snakemake Expected Inputs:
#   - snakemake@input[["cytopus"]] : Path to cytopus gene sets
#   - snakemake@input[["spectra_GP_activation_WMW"]]: Path to spectra's 
#                                                     differential activation
#                                                     analysis results
#   - snakemake@input[["spectra_GP_activation_LMM"]]: Path to spectra's 
#                                                     differential activation
#                                                     analysis results
#   - snakemake@input[["cNMF_GP_activation_WMW"]]: Path to cNMF's 
#                                                     differential activation
#                                                     analysis results
#   - snakemake@input[["cNMF_GP_activation_LMM"]]: Path to cNMF's 
#                                                     differential activation
#                                                     analysis results
# Snakemake Expected Outputs:
#   - snakemake@output[["table"]]: Destination path for the final comparison 
#                                  table generated by the script
# Snakemake Expected Params:
#   - snakemake@params[["enrichment_dir"]]: Path to enrichment analysis results
#   - snakemake@params[["case"]] : Name of the case condition in the metadata
#   - snakemake@params[["padj_thresh"]] : Significance threshold for enrichment
#                                         Results to be included in the table
#                                       
# ==============================================================================

# Setup Logging ----------------------------------------------------------------
# Redirect all output and messages to the Snakemake log file
log <- file(snakemake@log[[1]], open="wt")
sink(log)
sink(log, type="message")

# Load Libraries ---------------------------------------------------------------
suppressPackageStartupMessages({
        library(tidyverse)
        library(jsonlite)
        library(readxl)
})

message("Starting R script \"make_comp_table.R\"...")

# 1. Load Data ####
# ------------------------------------------------------------------------------
message("Loading cytopus gene sets list from: ",
        snakemake@input[["cytopus"]])
cytopus <- read_json(snakemake@input[["cytopus"]])
cytopus <- unlist(cytopus, recursive = FALSE)
message("Done")
message("Loading case condition name: ", snakemake@params[["case"]])
case <- snakemake@params[["case"]]
message("Done")
message("Loading p-value threshold : ", snakemake@params[["padj_thresh"]])
padj_thresh <- snakemake@params[["padj_thresh"]]
message("Done")
message("Loading spectra differential gene programs activation data from: ",
        snakemake@input[["spectra_GP_activation_WMW"]])
spectra_WMW <- read_csv(snakemake@input[["spectra_GP_activation_WMW"]]) %>% 
        dplyr::select(cell_type,
                      program,
                      FDR,
                      effect_size) %>%
        mutate(cell_type = gsub("/","_", cell_type)) %>% 
        mutate(program_short = str_split_i(str_split_i(program, "-X-", 3),fixed("-(ORA)"),1)) %>%
        dplyr::rename("FDR_wmw_spectra" = "FDR", "effect_size_wmw_spectra" = "effect_size")
message("Done")
message("Loading spectra differential gene programs activation data from: ",
        snakemake@input[["spectra_GP_activation_LMM"]])
spectra_LMM <- read_csv(snakemake@input[["spectra_GP_activation_LMM"]]) %>%
        dplyr::filter(term == paste0("diagnosis",case)) %>% 
        dplyr::select(cell_type, program, FDR, log2FC) %>%
        mutate(cell_type = gsub("/","_", cell_type)) %>% 
        mutate(program_short = str_split_i(str_split_i(program, "-X-", 3),fixed("-(ORA)"),1)) %>% 
        dplyr::rename("FDR_lmm_spectra"="FDR", "log2FC_lmm_spectra"="log2FC")
message("Done")
message("Loading cNMF differential gene programs activation data from: ",
        snakemake@input[["cNMF_GP_activation_WMW"]])
cNMF_WMW <- read_csv(snakemake@input[["cNMF_GP_activation_WMW"]]) %>% 
        dplyr::select(cell_type,
                      program,
                      FDR,
                      effect_size) %>%
        mutate(cell_type = gsub("/","_", cell_type)) %>% 
        mutate(program_short = str_split_i(str_split_i(program, "-X-", 3),fixed("-(ORA)"),1)) %>%
        dplyr::rename("FDR_wmw_cNMF" = "FDR", "effect_size_wmw_cNMF" = "effect_size")
message("Done")
message("Loading cNMF differential gene programs activation data from: ",
        snakemake@input[["cNMF_GP_activation_LMM"]])
cNMF_LMM <- read_csv(snakemake@input[["cNMF_GP_activation_LMM"]]) %>%
        dplyr::filter(term == paste0("diagnosis",case)) %>% 
        dplyr::select(cell_type, program, FDR, log2FC) %>%
        mutate(cell_type = gsub("/","_", cell_type)) %>% 
        mutate(program_short = str_split_i(str_split_i(program, "-X-", 3),fixed("-(ORA)"),1)) %>%
        dplyr::rename("FDR_lmm_cNMF"="FDR", "log2FC_lmm_cNMF"="log2FC")
message("Done")

# 2. join different methods (leave enrichments for later) ####
# ------------------------------------------------------------------------------
message("Merging spectra WMW and spectra LMM ...")
spectra_tests <- spectra_LMM %>% 
                        full_join(spectra_WMW %>% dplyr::select(-c(program_short)), by = c("cell_type", "program")) %>% 
                        dplyr::relocate(program_short, .after=program)
message("Done")
message("Merging cNMF WMW and cNMF LMM ...")
cNMF_tests <- cNMF_LMM %>% 
                        full_join(cNMF_WMW %>% dplyr::select(-c(program_short)), by =c("cell_type", "program")) %>% 
                        dplyr::relocate(program_short, .after=program)
message("Done")
message("Merging together spectra and cNMF ...")
comp_table <- spectra_tests %>% 
                        full_join(cNMF_tests, by = c("cell_type", "program_short"), suffix = c("_spectra", "_cNMF")) %>% 
                        dplyr::relocate(program_cNMF, .after=program_spectra)


# 3. Retrieve all GSEA and ORA output files ####
# ------------------------------------------------------------------------------
message("Retrieving GSEA and ORA output files ...")
paths <- list.files(snakemake@params[["enrichment_dir"]],
                    pattern = "csv",
                    full.names = TRUE,
                    recursive = TRUE)
message("Done")

# 4. Load GSEA results and concat to comparison table ####
# ------------------------------------------------------------------------------
message("Loading GSEA results ...")
for (DEG_set in c("sc", "pb")) {
        if(!is_empty(paths[grepl(paste0("gsea/", DEG_set), paths)])){
                current_paths <- paths[grepl(paste0("gsea/", DEG_set), paths)]
                enrich_res <- lapply(current_paths, function(path){
                        celltype <- str_split_i(path, "/", -1)
                        celltype <- str_split_i(celltype, "\\.",1)
                        df <- read_csv(path)
                        return(data_frame(celltype,
                                          df$pathway,
                                          df$padj,
                                          df$ES,
                                          df$NES))
                })
                enrich_res <- bind_rows(enrich_res)
        }else{
                enrich_res <- data.frame(NA, NA, NA, NA, NA)
        }
        colnames(enrich_res) <- c("cell_type",
                                  "program",
                                  paste0("padj_GSEA_", DEG_set),
                                  paste0("ES_GSEA_", DEG_set),
                                  paste0("NES_GSEA_", DEG_set))
        # Bind to gigatable
        comp_table <- comp_table %>% 
                full_join(enrich_res %>% 
                                  dplyr::rename("program_short" = "program"), 
                          by = c("cell_type", "program_short"))
}
message("Done")

# 5. Load ORA results and concat to comparison table ####
# ------------------------------------------------------------------------------
message("Loading ORA results ...")
# ORA UP
for (DEG_set in c("sc", "pb", "both")) {
        # Get ORA results for DEGs according to 'DEG_set'
        if(!is_empty(paths[grepl(paste0("ora/", DEG_set,".+UP"), paths)])){
                current_paths <- paths[grepl(paste0("ora/", DEG_set,".+UP"), paths)]
                enrich_res <- lapply(current_paths, function(path){
                        celltype <- str_split_i(path, "/", -1)
                        celltype <- str_split_i(celltype, "\\.",1)
                        celltype <- str_split_i(celltype, "_UP",1)
                        df <- read_csv(path)
                        df <- df %>% 
                                mutate(GeneRatio = (as.numeric(str_split_i(GeneRatio, "/",1))/as.numeric(str_split_i(GeneRatio, "/",2))))
                        return(data_frame(celltype,
                                          df$ID,
                                          df$p.adjust,
                                          df$GeneRatio))
                })
                enrich_res <- bind_rows(enrich_res)
        }else{
                enrich_res <- data.frame(NA, NA, NA, NA)
        }
        colnames(enrich_res) <- c("cell_type",
                                  "program",
                                  paste0("padj_ORA_UP_", DEG_set),
                                  paste0("GeneRatio_ORA_UP_", DEG_set))
        enrich_res <- enrich_res %>% dplyr::filter(.[[3]]<padj_thresh)
        comp_table <- comp_table %>% 
                full_join(enrich_res %>%
                                  dplyr::rename("program_short" = "program"),
                          by = c("cell_type", "program_short"))
}

# ORA DOWN
for (DEG_set in c("sc", "pb", "both")) {
        if(!is_empty(paths[grepl(paste0("ora/", DEG_set,".+DOWN"), paths)])){
                current_paths <- paths[grepl(paste0("ora/", DEG_set,".+DOWN"), paths)]
                enrich_res <- lapply(current_paths, function(path){
                        celltype <- str_split_i(path, "/", -1)
                        celltype <- str_split_i(celltype, "\\.",1)
                        celltype <- str_split_i(celltype, "_DOWN",1)
                        df <- read_csv(path)
                        df <- df %>% mutate(GeneRatio = (as.numeric(str_split_i(GeneRatio, "/",1))/as.numeric(str_split_i(GeneRatio, "/",2))))
                        return(data_frame(celltype,
                                          df$ID,
                                          df$p.adjust,
                                          df$GeneRatio))
                })
                enrich_res <- bind_rows(enrich_res)
        }else{
                enrich_res <- data.frame(NA, NA, NA, NA)
        }
        colnames(enrich_res) <- c("cell_type",
                                  "program",
                                  paste0("padj_ORA_DOWN_", DEG_set),
                                  paste0("GeneRatio_ORA_DOWN_",DEG_set))
        enrich_res <- enrich_res %>% dplyr::filter(.[[3]]<padj_thresh)
        comp_table <- comp_table %>% 
                full_join(enrich_res %>%
                                  dplyr::rename("program_short" = "program"),
                          by = c("cell_type", "program_short"))
}
message("Done")

# 6. Reformat gene programs name and size ####
# ------------------------------------------------------------------------------
message("Adding gene program size to each row ...")
geneset_size    <- lapply(cytopus, length)
geneset_size_df    <- data_frame("program_short" = names(geneset_size),
                                 "geneset_size"= unname(unlist(geneset_size)))
# Add new column
comp_table    <- comp_table %>%
        left_join(geneset_size_df, by = "program_short") %>%
        relocate(geneset_size, .after = program_short)
message("Done")

message("Reformatting gene program name ...")
comp_table <- comp_table %>%
        mutate(program_specificity = str_split_i(program_short, "_",1)) %>%
        relocate(program_specificity, .before = "program_short")
message("Done")

# 7. Save comparison table ####
# ------------------------------------------------------------------------------
message("Saving comparison table ...")
write_csv(comp_table, snakemake@output[["table"]])
message("Done")

# Close Logging ----------------------------------------------------------------
sink(type="message")
sink()